package pyrocosm

import soundness.*

// What every tool does to a TEL document read from a file before parsing it: prepends the
// `tel 1.0` header the file may omit, and says how many lines it added, so that a position in
// the parsed document can be given in the file's own lines.
object Tels:
  def headed(text: Text): (Text, Int) =
    if text.trim.starts(t"tel ") then (text, 0) else (t"tel 1.0\n\n$text", 2)
