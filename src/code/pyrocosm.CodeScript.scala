package pyrocosm
import soundness.*

// The script of the code blocks, from the module's resources: it plays an animated block, keeps
// the page's clock and switches a block's alternatives. A page which is not a Pyrocosm
// application's serves `text` as a script of its own, and the script wires the page; the web
// module serves it at the head of its own script.
object CodeScript:
  lazy val text: Text =
    val stream = getClass.getResourceAsStream("/pyrocosm-code.js")
    if stream == null then t"" else new String(stream.nn.readAllBytes(), "UTF-8").tt
